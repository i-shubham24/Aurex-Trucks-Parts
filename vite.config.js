import path from 'node:path'
import { pathToFileURL } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

/* After a production build, write app.html, 404.html, sitemap-pages.xml and crawler-readable HTML for each catalogue page (scripts/prerender.js).
   app.html and 404.html must exist (vercel.json routes to them), so failing to write them fails the build.
   Snapshot failures (API down, template changed) only skip the snapshots. Set PRERENDER=false to skip those. */
function prerenderPlugin() {
  let root, outDir
  return {
    name: 'aurex-prerender',
    apply: 'build',
    configResolved(config) {
      root = config.root
      outDir = path.resolve(config.root, config.build.outDir)
    },
    async closeBundle() {
      // Loaded here, not imported at the top: a top-level import makes the app files it uses (src/seo, src/data)
      // part of this config, so editing them would restart the dev server.
      const { prerender, writeShellPages } = await import(pathToFileURL(path.join(root, 'scripts/prerender.js')).href)
      await writeShellPages(outDir)
      if (process.env.PRERENDER === 'false') return
      try {
        const pages = await prerender(outDir)
        console.log(`[prerender] wrote ${pages} page snapshots`)
      } catch (err) {
        console.warn(`[prerender] skipped: ${err.message}`)
      }
    },
  }
}

// The sitemap is generated by the API from the live catalogue; vercel.json rewrites it the same way in production.
const sitemapProxy = {
  '/sitemap.xml': { target: 'http://localhost:5001', rewrite: () => '/api/v1/sitemap.xml' },
}

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), tailwindcss(), prerenderPlugin()],
  server: {
    proxy: { '/api': 'http://localhost:5001', ...sitemapProxy },
    watch: {
      ignored: [
        '**/truck-parts-admin/**',
        '**/truck-parts-api/**',
        '**/*.pdf',
        '**/*.backup',
        '**/.git/**',
      ],
    },
  },
  // Production builds call the API on their own origin (/api/v1, rewritten by vercel.json),
  // so `vite preview` needs the same hop to the local API.
  preview: {
    proxy: { '/api': 'http://localhost:5001', ...sitemapProxy },
  },
  build: {
    sourcemap: false,
  },
})
